// glyph index for an ASCII char; returns 11 (blank glyph) for unsupported chars
static inline uint8_t fontIndex(char c) {
    if (c == '%') return 43;
    if (c == '-') return 44;
    if (c >= '0' && c <= 'Z') return (uint8_t)(c - '0');
    return 11;
}
